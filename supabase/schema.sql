create table if not exists public.admin_users (
  id uuid primary key default gen_random_uuid(),
  name text not null check (char_length(name) between 2 and 100),
  email text not null unique,
  password_hash text not null,
  role text not null default 'admin' check (role in ('admin')),
  created_at timestamptz not null default now()
);

alter table public.admin_users enable row level security;

create table if not exists public.reservations (
  id bigint generated by default as identity primary key,
  name text not null,
  email text not null,
  reservation_date date not null,
  reservation_time time not null,
  guests smallint not null check (guests between 1 and 20),
  occasion text,
  notes text,
  status text not null default 'pending'
    check (status in ('pending', 'confirmed', 'cancelled')),
  created_at timestamptz not null default now()
);

alter table public.reservations
  add column if not exists status text not null default 'pending';

alter table public.reservations
  alter column status set default 'pending';

update public.reservations
set status = lower(trim(status));

alter table public.reservations
  drop constraint if exists reservations_status_check;

alter table public.reservations
  add constraint reservations_status_check
  check (status in ('pending', 'confirmed', 'cancelled'));

alter table public.reservations enable row level security;

create policy "Anyone can create reservations"
  on public.reservations for insert
  to anon, authenticated
  with check (true);

create table if not exists public.menu_items (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  description text,
  category text not null,
  price numeric(10, 2) not null check (price >= 0),
  image_url text,
  preparation_time integer,
  is_vegetarian boolean not null default false,
  is_available boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.menu_items enable row level security;

create policy "Anyone can view menu items"
  on public.menu_items for select
  to anon, authenticated
  using (true);

create policy "Admins can create menu items"
  on public.menu_items for insert
  to anon, authenticated
  with check (true);

insert into storage.buckets (id, name, public)
values ('menu-images', 'menu-images', true)
on conflict (id) do nothing;

create policy "Anyone can view menu images"
  on storage.objects for select
  to anon, authenticated
  using (bucket_id = 'menu-images');

create policy "Admins can upload menu images"
  on storage.objects for insert
  to anon, authenticated
  with check (bucket_id = 'menu-images');

create policy "Admins can delete menu images"
  on storage.objects for delete
  to anon, authenticated
  using (bucket_id = 'menu-images');

create or replace function public.set_menu_items_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists set_menu_items_updated_at on public.menu_items;
create trigger set_menu_items_updated_at
before update on public.menu_items
for each row execute function public.set_menu_items_updated_at();
